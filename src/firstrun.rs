//! Tool packs: which tools belong to a pack, the installer's pack list, and
//! the first-run hand-off from `setup.exe`.
//!
//! The installer writes the packs the user ticked to
//! `%APPDATA%\winsploit\first-run.yaml` (`packs: [recon, web]`). That file
//! alone never installs anything: on the next launch winsploit lists every
//! tool the packs resolve to and asks. The file is deleted once answered,
//! whether the answer was yes or no. Pack ids are checked against the loaded
//! catalog and anything unknown is ignored.

use std::collections::BTreeMap;
use std::path::{Path, PathBuf};

use serde::Deserialize;

use crate::registry::{self, Catalog, Launch, Tool};

#[derive(Deserialize, Default)]
struct FirstRunFile {
    #[serde(default)]
    packs: Vec<String>,
}

/// Where the installer leaves its choices.
pub fn path() -> Option<PathBuf> {
    std::env::var_os("APPDATA").map(|a| PathBuf::from(a).join("winsploit").join("first-run.yaml"))
}

/// Pack ids in a first-run file. Unreadable or malformed files give none.
pub fn read_packs(path: &Path) -> Vec<String> {
    let Ok(text) = std::fs::read_to_string(path) else {
        return Vec::new();
    };
    let file: FirstRunFile = serde_yaml::from_str(&text).unwrap_or_default();
    file.packs
}

/// The tools in pack `id`: a curated `packs:` entry of the catalog, else every
/// tool of that category. Datasets (wordlists) only come with the `wordlists`
/// pack itself, never with another category that happens to list them.
/// Unknown ids give nothing.
pub fn members<'a>(
    tools: &'a [Tool],
    packs: &BTreeMap<String, Vec<String>>,
    id: &str,
) -> Vec<&'a Tool> {
    if let Some(names) = packs.get(id) {
        return tools
            .iter()
            .filter(|t| names.iter().any(|n| n == &t.name))
            .collect();
    }
    tools
        .iter()
        .filter(|t| t.in_category(id) && (t.launch != Launch::Dataset || id == "wordlists"))
        .collect()
}

/// Tool names for several packs, in catalog order, each once.
pub fn resolve(catalog: &Catalog, ids: &[String]) -> Vec<String> {
    let mut chosen = vec![false; catalog.tools.len()];
    for id in ids {
        for m in members(&catalog.tools, &catalog.packs, id) {
            if let Some(i) = catalog.tools.iter().position(|t| t.name == m.name) {
                chosen[i] = true;
            }
        }
    }
    catalog
        .tools
        .iter()
        .zip(chosen)
        .filter(|(_, c)| *c)
        .map(|(t, _)| t.name.clone())
        .collect()
}

/// One pack as the installer shows it.
#[derive(Debug, PartialEq, Eq)]
pub struct PackInfo {
    pub id: String,
    pub label: String,
    pub count: usize,
}

/// Every pack with at least one tool: the category packs in dashboard order,
/// then the curated ones.
pub fn pack_list(catalog: &Catalog) -> Vec<PackInfo> {
    let mut ids: Vec<String> = catalog
        .tools
        .iter()
        .flat_map(|t| t.categories.iter().cloned())
        .collect();
    ids.sort_by(|a, b| (registry::category_rank(a), a).cmp(&(registry::category_rank(b), b)));
    ids.dedup();
    ids.extend(catalog.packs.keys().cloned());
    ids.into_iter()
        .filter_map(|id| {
            let count = members(&catalog.tools, &catalog.packs, &id).len();
            let label = if catalog.packs.contains_key(&id) {
                match id.as_str() {
                    "ctf" => "CTF starter".to_string(),
                    _ => registry::category_label(&id),
                }
            } else {
                registry::category_label(&id)
            };
            (count > 0).then_some(PackInfo { id, label, count })
        })
        .collect()
}

/// Inno Setup include with one `Pack(...)` line per pack, so the installer's
/// checkbox list is generated from `tools.yaml` and can't drift from it.
/// Format: `id|label|count|default` where default is 1 for the packs ticked
/// out of the box (none of the datasets).
pub fn iss_include(catalog: &Catalog) -> String {
    let mut out = String::from(
        "; generated by `winsploit packs --iss` from tools.yaml. Do not edit.\n\
         #define PackList \"",
    );
    let items: Vec<String> = pack_list(catalog)
        .iter()
        .map(|p| {
            let on = u8::from(p.id == "ctf");
            format!("{}|{}|{}|{}", p.id, p.label, p.count, on)
        })
        .collect();
    out.push_str(&items.join(";"));
    out.push_str("\"\n");
    out
}

/// The installer's pending choice, waiting for the user's yes or no.
#[derive(Debug)]
pub struct Pending {
    /// Tool names to install, in catalog order.
    pub names: Vec<String>,
    path: PathBuf,
}

impl Pending {
    /// Read `file`; if it names packs that resolve to tools, return them to be
    /// confirmed. A file that resolves to nothing is deleted right away.
    pub fn load_from(file: &Path, catalog: &Catalog) -> Option<Pending> {
        if !file.is_file() {
            return None;
        }
        let names = resolve(catalog, &read_packs(file));
        if names.is_empty() {
            let _ = std::fs::remove_file(file);
            return None;
        }
        Some(Pending {
            names,
            path: file.to_path_buf(),
        })
    }

    pub fn load(catalog: &Catalog) -> Option<Pending> {
        Self::load_from(&path()?, catalog)
    }

    /// The user answered: the file has done its job either way.
    pub fn finish(self) -> Vec<String> {
        let _ = std::fs::remove_file(&self.path);
        self.names
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    fn cat() -> Catalog {
        registry::parse(include_str!("../tools.yaml")).unwrap()
    }

    fn tmp(name: &str) -> PathBuf {
        let d = std::env::temp_dir().join(format!("winsploit-test-{}-{name}", std::process::id()));
        let _ = std::fs::remove_dir_all(&d);
        std::fs::create_dir_all(&d).unwrap();
        d
    }

    #[test]
    fn category_pack_lists_that_category_and_skips_datasets() {
        let c = cat();
        let web = members(&c.tools, &c.packs, "web");
        assert!(web.iter().any(|t| t.name == "ffuf"));
        assert!(web.iter().all(|t| t.launch != Launch::Dataset));
        let words = members(&c.tools, &c.packs, "wordlists");
        assert!(words.iter().any(|t| t.launch == Launch::Dataset));
    }

    #[test]
    fn unknown_packs_are_ignored() {
        let c = cat();
        assert!(resolve(&c, &["nope".into(), "..\\x".into()]).is_empty());
        let one = resolve(&c, &["nope".into(), "ctf".into()]);
        assert_eq!(one.len(), c.packs["ctf"].len());
    }

    #[test]
    fn resolve_dedupes_and_keeps_catalog_order() {
        let c = cat();
        let names = resolve(&c, &["web".into(), "recon".into(), "web".into()]);
        let mut sorted = names.clone();
        sorted.dedup();
        assert_eq!(names, sorted);
        let pos = |n: &str| c.tools.iter().position(|t| t.name == n).unwrap();
        assert!(names.windows(2).all(|w| pos(&w[0]) < pos(&w[1])));
    }

    #[test]
    fn pack_list_has_counts_and_ctf_last() {
        let c = cat();
        let list = pack_list(&c);
        assert_eq!(list.last().unwrap().id, "ctf");
        assert!(list
            .iter()
            .all(|p| p.count == members(&c.tools, &c.packs, &p.id).len()));
        let inc = iss_include(&c);
        assert!(inc.contains("ctf|CTF starter|"));
        assert!(inc.contains("recon|Recon|"));
    }

    #[test]
    fn a_file_alone_is_only_a_pending_question() {
        let c = cat();
        let dir = tmp("pending");
        let f = dir.join("first-run.yaml");
        std::fs::write(&f, "packs: [ctf, bogus]\n").unwrap();
        let p = Pending::load_from(&f, &c).unwrap();
        assert_eq!(p.names.len(), c.packs["ctf"].len());
        // loading did not consume the file: the answer does
        assert!(f.exists());
        let names = p.finish();
        assert!(!names.is_empty());
        assert!(!f.exists());
        let _ = std::fs::remove_dir_all(dir);
    }

    #[test]
    fn useless_or_broken_files_are_deleted_without_asking() {
        let c = cat();
        let dir = tmp("useless");
        for (i, body) in ["packs: [bogus]\n", "packs: [", "", "packs: []\n"]
            .iter()
            .enumerate()
        {
            let f = dir.join(format!("f{i}.yaml"));
            std::fs::write(&f, body).unwrap();
            assert!(Pending::load_from(&f, &c).is_none());
            assert!(!f.exists(), "{body:?} left behind");
        }
        assert!(Pending::load_from(&dir.join("missing.yaml"), &c).is_none());
        let _ = std::fs::remove_dir_all(dir);
    }
}
